// Продажа остатка: кнопка у ордера покупки продавала ВЕСЬ его объём, даже
// если часть монеты уже ушла другим ордером. Биржа такую продажу отклоняет
// целиком — заказано больше, чем свободно.
const fs = require('fs');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const d = fs.readFileSync('public/index.html', 'utf8');
const m = fs.readFileSync('public/mobile/index.html', 'utf8');

console.log('\nСколько продавать');
{
  // Меньшее из двух: объём этого ордера и то, что осталось по монете.
  const pick = (ordFilled, remaining) => Math.max(0, Math.min(ordFilled, remaining));
  ok(pick(41421.9, 21519.8) === 21519.8, 'после частичной продажи предлагается остаток');
  ok(pick(41421.9, 41421.9) === 41421.9, 'если ничего не продано — весь объём ордера');
  ok(pick(1000, 5000) === 1000, 'больше, чем было в ордере, не предлагается');
  ok(pick(1000, 0) === 0, 'когда не осталось ничего — ноль, а не отрицательное');

  // Стоимость делится в той же доле: иначе прибыль считается против денег,
  // которых в этой части сделки нет.
  const cost = (total, ordFilled, sellNow) => ordFilled > 0 ? total * (sellNow / ordFilled) : 0;
  ok(Math.abs(cost(2491.03, 41421.9, 21519.8) - 1294.14) < 0.5,
    'основание делится пропорционально', '$' + cost(2491.03, 41421.9, 21519.8).toFixed(2));
  ok(cost(2491.03, 0, 0) === 0, 'нулевой ордер не делит на ноль');
}

console.log('\nОбе вёрстки');
for (const [name, h, mark] of [['index.html', d, '_sellNow'], ['mobile/index.html', m, '_sellNow']]) {
  ok(h.includes('Math.min(_ordFilled, totalFilled)'), name + ': берётся меньшее из объёма ордера и остатка');
  ok(/_sellCost = _ordFilled > 0/.test(h), name + ': стоимость делится в той же доле');
  ok(/_partial/.test(h), name + ': частичный случай помечен для подсказки');
  ok(!/'\$\{o\.filled_size\}', \$\{parseFloat\(o\.average_filled_price\)/.test(h),
    name + ': прежней передачи полного объёма не осталось');
}

console.log('\nСторож свободного остатка');
{
  // Монеты могут быть заперты в открытом ордере: тогда продавать нечего, и
  // сказать об этом надо ДО отправки, а не показывать отказ биржи.
  for (const [name, h] of [['index.html', d], ['mobile/index.html', m]]) {
    ok(/Продавать нечего/.test(h), name + ': отказ объяснён словами');
    ok(/заморожено в открытом ордере/.test(h), name + ': названа причина — открытый ордер');
    ok(/Сними открытый ордер продажи и повтори/.test(h), name + ': сказано, что делать');
    ok(/avail \+ 1e-9 < sz/.test(h), name + ': сравнение со свободным остатком, а не с выбранным');
  }
}

console.log(bad ? '\n' + bad + ' проверок не прошло' : '\nвсе проверки прошли');
process.exit(bad ? 1 : 0);
