// Запись прибыли по незакрытой позиции.
//
// Прежде хватало одной исполненной продажи, а прибылью считалось «сколько
// вышло минус сколько вошло». Пока часть монет ещё твоя, это не прибыль, а
// вложенные деньги: по CRO после продажи половины кнопка предлагала записать
// −$1291.91 убытка, тогда как оставшиеся 21 516 монет стоили примерно
// столько же. Один клик — и в историю уходит ложная запись.
const fs = require('fs');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const d = fs.readFileSync('public/index.html', 'utf8');
const m = fs.readFileSync('public/mobile/index.html', 'utf8');

console.log('\nУсловие записи');
{
  // Воспроизводим условие как есть
  const can = (buys, sells, totalFilled, avgBuy) => {
    const restUsd = totalFilled * (avgBuy || 0);
    const positionClosed = totalFilled <= 0 || restUsd < 1;
    return buys > 0 && sells > 0 && positionClosed;
  };
  // Ровно случай с CRO: продана половина, остаток стоит $1292
  ok(can(1, 1, 21516.2, 0.06004784) === false, 'по половине проданной позиции записывать нельзя');
  ok(can(1, 1, 0, 0.06) === true, 'закрытая позиция записывается');
  // Пыль после продажи остаётся почти всегда — на ней кнопка блокироваться не должна
  ok(can(1, 1, 5, 0.06) === true, 'пыль на $0.30 считается закрытием', '$' + (5 * 0.06).toFixed(2));
  ok(can(1, 1, 20, 0.06) === false, 'остаток на $1.20 закрытием не считается');
  ok(can(1, 0, 0, 0.06) === false, 'без продажи записывать нечего');
  ok(can(0, 1, 0, 0.06) === false, 'без покупки тоже');
  // Нулевая средняя цена не должна открывать лазейку
  ok(can(1, 1, 21516.2, 0) === true, 'при неизвестной цене остаток оценить нечем — не блокируем',
    'известное ограничение: без цены остаток в долларах не посчитать');
}

console.log('\nОбе вёрстки');
for (const [name, h] of [['index.html', d], ['mobile/index.html', m]]) {
  ok(/const positionClosed = totalFilled <= 0 \|\| restUsd < 1;/.test(h), name + ': признак закрытия считается');
  ok(/canSaveProfit = filledBuys\.length > 0 && filledSells\.length > 0 && positionClosed/.test(h),
    name + ': запись требует закрытой позиции');
  ok(/ещё открыта/.test(h), name + ': сказано, почему записывать рано');
}
// Остаток ушёл в подсказку: на кнопке он менял её ширину втрое, и строка
// перекладывалась при каждой перерисовке.
ok(/осталось \$\{fmtSize\(totalFilled\)\}/.test(d), 'десктоп: остаток назван в подсказке');
ok(/title="\$\{openTitle\}"/.test(d), 'подсказка привязана к кнопке');
ok(/\.save-profit-btn \{ min-width: 132px/.test(d), 'ширина кнопки задана заранее — строка не прыгает');
ok(/осталось \$\{fmt\(totalFilled\)\}/.test(m), 'мобильная: назван остаток');

console.log('\nЧисло, которое записалось бы по ошибке');
{
  const boughtUsd = 2491.03, soldNet = 1199.12;
  const wrong = -(boughtUsd - soldNet);
  ok(Math.abs(wrong + 1291.91) < 0.05, 'прежняя формула дала бы −$1291.91', '$' + wrong.toFixed(2));
  // А остаток стоит примерно столько же — то есть убытка нет вовсе
  const restValue = 21516.2 * 0.05965;
  ok(Math.abs(restValue - (boughtUsd - soldNet)) < 20, 'при этом остаток стоит примерно столько же',
    '$' + restValue.toFixed(2));
}

console.log(bad ? '\n' + bad + ' проверок не прошло' : '\nвсе проверки прошли');
process.exit(bad ? 1 : 0);
