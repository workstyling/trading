// Запись прибыли по незакрытой позиции.
//
// Прежде хватало одной исполненной продажи, а прибылью считалось «сколько
// вышло минус сколько вошло». Пока часть монет ещё твоя, это не прибыль, а
// вложенные деньги: по CRO после продажи половины кнопка предлагала записать
// −$1291.91 убытка, тогда как оставшиеся 21 516 монет стоили примерно
// столько же. Один клик — и в историю уходит ложная запись.
const fs = require('fs');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const d = fs.readFileSync('public/index.html', 'utf8');
const m = fs.readFileSync('public/mobile/index.html', 'utf8');

console.log('\nУсловие записи');
{
  // Воспроизводим условие как есть
  const can = (buys, sells, totalFilled, avgBuy) => {
    const restUsd = totalFilled * (avgBuy || 0);
    const OVERSOLD_USD = 0.05;
    const restPriced = avgBuy > 0;
    const oversold = restPriced ? restUsd < -OVERSOLD_USD : totalFilled < 0;
    const positionClosed = !oversold && restUsd < 1;
    return buys > 0 && sells > 0 && positionClosed;
  };
  // Ровно случай с CRO: продана половина, остаток стоит $1292
  ok(can(1, 1, 21516.2, 0.06004784) === false, 'по половине проданной позиции записывать нельзя');
  ok(can(1, 1, 0, 0.06) === true, 'закрытая позиция записывается');
  // Пыль после продажи остаётся почти всегда — на ней кнопка блокироваться не должна
  ok(can(1, 1, 5, 0.06) === true, 'пыль на $0.30 считается закрытием', '$' + (5 * 0.06).toFixed(2));
  ok(can(1, 1, 20, 0.06) === false, 'остаток на $1.20 закрытием не считается');
  ok(can(1, 0, 0, 0.06) === false, 'без продажи записывать нечего');
  ok(can(0, 1, 0, 0.06) === false, 'без покупки тоже');
  // Нулевая средняя цена не должна открывать лазейку
  ok(can(1, 1, 21516.2, 0) === true, 'при неизвестной цене остаток оценить нечем — не блокируем',
    'известное ограничение: без цены остаток в долларах не посчитать');

  // ОТРИЦАТЕЛЬНЫЙ ОСТАТОК — НЕ ЗАКРЫТИЕ.
  //
  // Продано больше, чем видно купленного: часть покупок выключена руками или
  // лежит за краем окна ордеров. Раньше такое считалось закрытой позицией: по
  // CP выключение покупки давало остаток −35 230 и кнопку «записать +$629.44»
  // по позиции, где ещё лежат 32 705 монет.
  ok(can(1, 1, -35230, 0.0178) === false, 'продано больше купленного — записывать нельзя');
  ok(can(1, 1, -1, 0.06) === false, 'и минус на $0.06 тоже не закрытие');

  // НО МИНУС МЕРЯЕТСЯ В ДЕНЬГАХ, А НЕ В МОНЕТАХ.
  //
  // Размеры приходят с биржи с восемью знаками, и на честно закрытой позиции
  // суммы покупок и продаж сходятся не до последнего знака. По DASH продажа
  // 7.88 против покупки 7.88 оставила −0.00000006 монеты, и кнопка объявила
  // «часть покупок за краем окна» по позиции, где за краем ничего не было:
  // настоящие +$10.51 записать было нельзя.
  ok(can(1, 1, -0.00000006, 57.2013) === true, 'пыль в минус — это округление, а не пропавшая покупка',
    '$' + Math.abs(-0.00000006 * 57.2013).toFixed(6));
  // На копеечной монете тот же порог: важно, сколько это денег
  ok(can(1, 1, -1000, 0.000005) === true, 'тысяча монет по полкопейки — те же полкопейки');
  ok(can(1, 1, -300000, 0.000005) === false, 'а на $1.50 недостающих покупок — уже нет');
  // Пропавшая покупка это ордер, а ордера меньше доллара биржа не принимает:
  // порог стоит сильно ниже самого маленького, что могло пропасть.
  ok(can(1, 1, -0.02, 57.2013) === false, 'минус на доллар с лишним — это пропавшая покупка',
    '$' + Math.abs(-0.02 * 57.2013).toFixed(2));
  // Без цены остаток в деньги не перевести — тогда как раньше, по количеству
  ok(can(1, 1, -35230, 0) === false, 'без цены покупки минус блокирует по-старому');
}

console.log('\nСостав ордеров одинаков для сумм и для записи');
{
  // Выключенные ордера убирались из сумм, но оставались в списках, по которым
  // решается «позиция закрыта» и что уходит в историю. Один состав на всё.
  ok(/const active = orders\.filter\(o => !mutedOrders\.includes\(o\.order_id\)\)/.test(d),
    'десктоп: состав считается один раз');
  ok(/active\.forEach\(o => \{/.test(d), 'и суммы идут по нему');
  ok(/const filledBuys = active\.filter/.test(d) && /const filledSells = active\.filter/.test(d),
    'и списки для записи тоже');
  ok(!/const filledBuys = orders\.filter/.test(d), 'полного списка ордеров в записи не осталось');

  // Телефон выключения не показывает, но обязан их сохранить: он отправлял
  // muted: [] и стирал то, что выключено на десктопе.
  ok(/muted: _mutedFromServer/.test(m), 'телефон возвращает список выключенных как есть');
  ok(!/JSON\.stringify\(\{ selected: selectedOrders, muted: \[\] \}\)/.test(m),
    'и больше не стирает его пустым списком');
}

console.log('\nОбе вёрстки');
for (const [name, h] of [['index.html', d], ['mobile/index.html', m]]) {
  ok(/const OVERSOLD_USD = 0\.05;/.test(h), name + ': порог минуса задан в деньгах');
  ok(/const oversold = restPriced \? restUsd < -OVERSOLD_USD : totalFilled < 0;/.test(h) &&
    /const positionClosed = !oversold && restUsd < 1;/.test(h),
    name + ': признак закрытия считается, и минус на деньги закрытием не считается');
  ok(!/const oversold = totalFilled < 0;/.test(h), name + ': прежней проверки по монетам не осталось');
  ok(/canSaveProfit = filledBuys\.length > 0 && filledSells\.length > 0 && positionClosed/.test(h),
    name + ': запись требует закрытой позиции');
  ok(/ещё открыта/.test(h), name + ': сказано, почему записывать рано');
  // «-0.000000» в остатке читается как поломка, а это та же пыль
  ok(/const filledShown = restPriced && Math\.abs\(restUsd\) < 0\.01 \? 0 : totalFilled;/.test(h),
    name + ': остаток дешевле цента показывается нулём');
  ok(!/\$\{fmtSize\(totalFilled\)\} \$\{coin\} <span id="realBal_/.test(h) &&
    !/monitor-stat-val">\$\{totalFilled\.toFixed/.test(h),
    name + ': и в самой строке остатка тоже');
  // Минус теперь назван деньгами: по количеству монет его не оценить на глаз
  ok(/не хватает покупок примерно на \$\$\{Math\.abs\(restUsd\)\.toFixed\(2\)\}/.test(h),
    name + ': сказано, на сколько денег не хватает покупок');
}
// Остаток ушёл в подсказку: на кнопке он менял её ширину втрое, и строка
// перекладывалась при каждой перерисовке.
ok(/осталось \$\{fmtSize\(totalFilled\)\}/.test(d), 'десктоп: остаток назван в подсказке');
ok(/title="\$\{openTitle\}"/.test(d), 'подсказка привязана к кнопке');
ok(/\.save-profit-btn \{ min-width: 132px/.test(d), 'ширина кнопки задана заранее — строка не прыгает');
ok(/осталось \$\{fmt\(totalFilled\)\}/.test(m), 'мобильная: назван остаток');

console.log('\nЧисло, которое записалось бы по ошибке');
{
  const boughtUsd = 2491.03, soldNet = 1199.12;
  const wrong = -(boughtUsd - soldNet);
  ok(Math.abs(wrong + 1291.91) < 0.05, 'прежняя формула дала бы −$1291.91', '$' + wrong.toFixed(2));
  // А остаток стоит примерно столько же — то есть убытка нет вовсе
  const restValue = 21516.2 * 0.05965;
  ok(Math.abs(restValue - (boughtUsd - soldNet)) < 20, 'при этом остаток стоит примерно столько же',
    '$' + restValue.toFixed(2));
}

console.log(bad ? '\n' + bad + ' проверок не прошло' : '\nвсе проверки прошли');
process.exit(bad ? 1 : 0);
