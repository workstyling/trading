// Падающий нож: монета, которая сперва взлетела, а теперь откатывается.
//
// Панель зовёт покупать по падению от суточного максимума, но максимум бывает
// разного происхождения. Монета, выросшая за сутки на четверть и сдавшая 5% с
// пика, даёт тот же сигнал, что монета, весь день спокойно сползавшая вниз, —
// а это разные вещи: в первом случае покупается откат после разгона.
//
// Замер на 79 638 точках входа по 78 монетам за 25 суток, вход тот же
// (падение от суточного максимума 3%+), горизонт час:
//
//   за сутки выросла >+10%:  просадка −2.26%, ниже −3% в 23.7% случаев
//   за сутки около нуля:     просадка −0.77%, ниже −3% в  2.7% случаев
//   за сутки упала  <−10%:   просадка −2.01%, ниже −3% в 20.5% случаев
//
// Доля дошедших до цели у разогнанных ДАЖЕ ВЫШЕ — 86% против 68%. Размах
// больше в обе стороны, и по одной доле этого не видно. Поэтому пометка, а не
// запрет: запрещать то, у чего средний исход часа положительный, нечестно.
const fs = require('fs'), vm = require('vm');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const read = (p) => fs.readFileSync(p, 'utf8').split('\r\n').join('\n');

console.log('\nСервер отдаёт ход за сутки по каждой монете');
{
  const src = read('server.js');
  ok(/chg24Pct: sig\.chg24Pct/.test(src), 'ход за сутки попадает в строку скана');
  // Без покрытия суток это не ход за сутки, а ход за сколько получилось
  const sig = src.slice(src.indexOf('const dayCoverH'), src.indexOf('async function entrySpread'));
  ok(/chg24Pct: chg24/.test(sig), 'и берётся из того же расчёта, что и остальное');
}

for (const [name, file] of [['десктоп', 'public/index.html'], ['мобильная', 'public/mobile/index.html']]) {
  console.log('\n' + name);
  const h = read(file);
  const i = h.indexOf('const swingMark = (x) => {');
  ok(i > 0, 'пометка размаха есть');
  const body = h.slice(i, h.indexOf('const cell = (x)', i));

  const ctx = { Math, String };
  vm.createContext(ctx);
  vm.runInContext(h.slice(i, h.indexOf('\n        const cell = (x)', i)) + ';this.swingMark = swingMark;', ctx);
  const f = ctx.swingMark;

  ok(f({ chg24Pct: null }) === '', 'без данных ничего не рисуется');
  ok(f({ chg24Pct: 4 }) === '', 'спокойная монета не помечается');
  ok(f({ chg24Pct: -7 }) === '', 'и небольшое падение тоже');
  const up = f({ chg24Pct: 24.3 });
  ok(up.includes('24%') && up.includes(String.fromCharCode(8593)), 'разгон помечен со стрелкой вверх', up.replace(/<[^>]+>/g, ''));
  ok(/#f5843a/.test(up), 'и оранжевым — это предупреждение, а не запрет');
  const dn = f({ chg24Pct: -18.6 });
  ok(dn.includes('19%') && dn.includes(String.fromCharCode(8595)), 'обвал помечен со стрелкой вниз', dn.replace(/<[^>]+>/g, ''));
  ok(/#ff6b6b/.test(dn), 'и красным: у него ещё и средний исход часа отрицательный');
  // Порог ровно тот, на котором мерили
  ok(f({ chg24Pct: 10.1 }) !== '' && f({ chg24Pct: 9.9 }) === '', 'порог там же, где замер: ±10%');

  // Числа в подсказке должны быть измеренными, а не круглыми на глаз
  const tip = file.includes('mobile') ? h.slice(h.indexOf('const swingTip = (x) => {'), h.indexOf('const cell = (x)')) : body;
  ok(/2\.26/.test(tip) && /0\.77/.test(tip), 'в подсказке настоящие просадки');
  ok(/23\.7/.test(tip) && /2\.7/.test(tip), 'и доля уходов ниже −3%');
  ok(/2\.01/.test(tip) && /20\.5/.test(tip), 'для обвала тоже');
  ok(/79 638/.test(h), 'и сказано, на чём измерено');
  // Главная ловушка: у разогнанных доля дошедших ВЫШЕ, и без этой оговорки
  // пометка выглядит просто как «плохая монета»
  ok(/86% против 68%/.test(h), 'сказано, что доля дошедших у разогнанных выше');
}

console.log(bad ? '\nПЛОХО: ' + bad : '\nвсё зелено');
process.exit(bad ? 1 : 0);
