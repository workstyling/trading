// Глубины в стакане: обе отрицательные, лимит всегда минимум на шаг глубже
// стопа. Правило не косметика — стоп обязан сработать раньше, чем цена дойдёт
// до лимитной, иначе лимитка уйдёт по цене, которой в стакане уже нет.
const fs = require('fs'), vm = require('vm');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const h = fs.readFileSync('public/index.html', 'utf8');

const store = {};
const ctx = {
  safeStorage: { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = v; } },
  JSON, Number, Math, console,
};
vm.createContext(ctx);
{
  const a = h.indexOf("    const SELL_STEPS_KEY = 'sellSteps';");
  const b = h.indexOf('    // Лестница цен вниз от лучшего ask');
  vm.runInContext(h.slice(a, b), ctx);
}

console.log('\nПравило: лимит минимум на шаг глубже стопа');
{
  const f = ctx.sellDepthsFix;
  let d = f(-1, -2);
  ok(d.sd === -1 && d.ld === -2, 'разница в шаг проходит как есть', JSON.stringify(d));
  // Ровно случай из просьбы: ставлю стоп −1 — лимит сам становится −2
  d = f(-1, 0);
  ok(d.sd === -1 && d.ld === -2, 'стоп −1 подтягивает лимит на −2', JSON.stringify(d));
  d = f(-1, -1);
  ok(d.ld === -2, 'совпадение глубин не допускается');
  d = f(-3, -1);
  ok(d.sd === -3 && d.ld === -4, 'лимит мельче стопа опускается ниже стопа', JSON.stringify(d));
  // Уже глубже минимума — не трогаем: пользователь так задал осознанно
  d = f(-1, -7);
  ok(d.sd === -1 && d.ld === -7, 'лимит глубже минимума остаётся как был');
  // Стоп на уровне 0 — это лучший ASK, выше рынка. Стоп продажи срабатывает
  // при движении последней цены ВНИЗ к нему, поэтому такой сработал бы сразу и
  // биржа его отклоняет. Самый мелкий допустимый — −1.
  d = f(0, -1);
  ok(d.sd === -1 && d.ld === -2, 'стоп на лучшем ask не допускается, опускается на −1', JSON.stringify(d));

  console.log('\nГраницы и мусор');
  d = f(5, 3);
  ok(d.sd === -1 && d.ld === -2, 'положительные глубины зажимаются: выше рынка стопа не бывает', JSON.stringify(d));
  // Потолок поднят до 500 уровней: у CRO стакан отдаёт 490, и прежние 50 на
  // такой плотности были всего 2.2% ниже рынка — защита туда не дотягивалась.
  d = f(-9999, -9999);
  ok(d.sd === -499 && d.ld === -500, 'слишком глубоко зажимается по дну', JSON.stringify(d));
  d = f('мусор', null);
  ok(d.sd === -1 && d.ld === -2, 'нечисло даёт значения по умолчанию', JSON.stringify(d));
  d = f(-1.7, -2.2);
  ok(Number.isInteger(d.sd) && Number.isInteger(d.ld), 'дробные округляются до уровней', JSON.stringify(d));
}

console.log('\nХранилище');
{
  ok(ctx.sellSteps('AAA').sd === -1 && ctx.sellSteps('AAA').ld === -2, 'по умолчанию стоп −1, лимит −2');
  ctx.sellStepsSave('AAA', { sd: -2, ld: -5 });
  ok(ctx.sellSteps('AAA').ld === -5, 'сохранённые глубины читаются');
  // Прежние записи мерили другое (стоп задавался «на сколько выше лимита»),
  // и толковать их как глубину нельзя.
  store['sellSteps'] = JSON.stringify({ BBB: { ask: 3, up: 2 } });
  const b = ctx.sellSteps('BBB');
  ok(b.sd === -1 && b.ld === -2, 'записи старого вида не толкуются как глубина, берутся умолчания', JSON.stringify(b));
  // Испорченное правило в хранилище чинится на чтении, а не уходит в ордер
  store['sellSteps'] = JSON.stringify({ CCC: { sd: -1, ld: -1 } });
  ok(ctx.sellSteps('CCC').ld === -2, 'нарушенное правило чинится при чтении');
}

console.log('\nЦены по глубине');
{
  // лестница: 0 = лучший ask, дальше биды
  const ladder = [10.2, 10.0, 9.9, 9.7, 9.4];
  const px = (sd, ld) => ({ stop: ladder[Math.min(-sd, ladder.length - 1)], limit: ladder[Math.min(-ld, ladder.length - 1)] });
  let r = px(-1, -2);
  ok(r.stop === 10.0 && r.limit === 9.9, 'стоп −1 это первый бид, лимит −2 второй', JSON.stringify(r));
  ok(r.stop > r.limit, 'стоп выше лимита — условие исполнения');
  r = px(-1, -3);
  ok(r.stop === 10.0 && r.limit === 9.7, 'глубины читаются как индексы лестницы');
  r = px(-10, -20);
  ok(r.stop === 9.4 && r.limit === 9.4, 'глубже стакана обе цены упираются в дно — это и помечается');
}

console.log('\nРазметка');
ok(/id="sellStepStop_\$\{coin\}"/.test(h), 'поле стопа есть');
ok(/id="sellStepAsk_\$\{coin\}"/.test(h), 'поле лимита есть');
ok(h.indexOf('sellStepStop_${coin}') < h.indexOf('sellStepAsk_${coin}'), 'стоп идёт первым');
ok(/value="\$\{_st\.sd\}"/.test(h) && /value="\$\{_st\.ld\}"/.test(h), 'подставляются сохранённые глубины');
ok(/min="-499" max="-1"/.test(h), 'стоп не мельче первого бида и достаёт вглубь');
ok(/min="-500" max="-2"/.test(h), 'лимит не мельче второго бида и достаёт вглубь');
ok(/в стакане всего ' \+ levels \+ ' уровней/.test(h), 'нехватка уровней названа, даже если схлопнулась только одна цена');
ok(/стоп ниже бида на/.test(h), 'расстояние стопа от цены показано процентом');
ok(/сработал бы мгновенно|отклонит/.test(h), 'подсказка объясняет, почему выше нельзя');
ok(!/стоп \+/.test(h), 'прежней подписи «стоп +» не осталось');
ok(/стакан короче запроса: стоп и лимит упёрлись в один уровень/.test(h), 'упор в дно назван');

console.log(bad ? '\n' + bad + ' проверок не прошло' : '\nвсе проверки прошли');
process.exit(bad ? 1 : 0);
