// Шанс вернуться к безубытку с текущей просадки.
//
// Убыток здесь не режут, а ждут возврата: три позиции висят двадцатый день на
// −29%, −57% и −63%. Решение «держать или резать» принималось ощущением.
//
// Замер: 45 самых ликвидных монет, 200 суток часовых свечей, 15 219 точек
// входа по тому же правилу, что у панели. Отсчёт идёт НЕ от покупки, а от
// момента, когда просадка впервые достигла порога, — так вопрос и стоит в
// жизни. Безубыток считается с кругом комиссии (+0.225%): продать по цене
// входа значит остаться в минусе.
//
//   просадка   за 7 сут   за 14   за 30   медиана ожидания
//     −10%        33%      52%     67%        7.0 сут
//     −20%        11%      24%     40%       11.3 сут
//     −30%         3%      12%     24%       14.3 сут
//     −45%         0%       9%     25%       15.6 сут (27 монет — шатко)
const fs = require('fs'), vm = require('vm');
let bad = 0;
const ok = (c, m, x) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'ПЛОХО') + '  ' + m + (x ? '   ' + x : '')); };
const read = (p) => fs.readFileSync(p, 'utf8').split('\r\n').join('\n');

console.log('\nДесктоп: колонка «Шанс к 0»');
{
  const h = read('public/index.html');
  const i = h.indexOf('const _RECOVER = [');
  const src = h.slice(i, h.indexOf('\n    function _jPnlCell', i));
  const ctx = { String, Math };
  vm.createContext(ctx);
  vm.runInContext(src + ';this.odds = _jRecoverOdds; this.cell = _jRecoverCell;', ctx);

  ok(ctx.odds(null) === null, 'без цены ничего не утверждаем');
  ok(ctx.odds(5) === null, 'позиция в плюсе — строки нет');
  ok(ctx.odds(-4) === null, 'мелкая просадка тоже не повод для справки');
  ok(ctx.odds(-12).w30 === 67, 'на −12% берётся полоса −10%', String(ctx.odds(-12).w30));
  ok(ctx.odds(-22).w30 === 40, 'на −22% — полоса −20%');
  // Полоса берётся по достигнутой глубине, а не по округлению вверх
  ok(ctx.odds(-29).w30 === 40, 'GWEI на −29% ещё в полосе −20%', String(ctx.odds(-29).w30));
  ok(ctx.odds(-31).w30 === 24, 'а на −31% уже в −30%');
  ok(ctx.odds(-10) != null, 'ровно −10% — это уже полоса −10%, а не «ещё нет»');
  ok(ctx.odds(-57).thin === true, 'глубже −45% помечено как шаткое: там всего 27 монет');
  ok(ctx.odds(-63).w30 === 25, 'и INX на −63% туда же');

  // Числа обязаны совпадать с замером, а не быть округлены на глаз
  ok(ctx.odds(-10).med === 7 && ctx.odds(-20).med === 11.3 && ctx.odds(-30).med === 14.3,
    'медианы ожидания те, что померены');

  const c = ctx.cell(-31);
  ok(/24%/.test(c), 'в ячейке доля за месяц', c.replace(/<[^>]+>/g, ''));
  ok(/#ff6b6b/.test(c), 'и она красная — три случая из четырёх не возвращаются');
  ok(/#f5c518/.test(ctx.cell(-22)), 'на −20% жёлтая');
  ok(/var\(--green\)/.test(ctx.cell(-12)), 'на −10% зелёная');
  ok(/ждали в среднем 14\.3 суток/.test(ctx.cell(-31)), 'в подсказке сказано, сколько ждали вернувшиеся');
  ok(/не прогноз по вашей монете/.test(ctx.cell(-31)), 'и что это доля случаев, а не предсказание');
  ok(/от момента, когда просадка достигла/.test(ctx.cell(-31)), 'и откуда идёт отсчёт');
  ok(/число шаткое/.test(ctx.cell(-57)), 'на большой глубине оговорка про выборку');
  ok(ctx.cell(3).includes('—'), 'у прибыльной позиции прочерк');

  ok(/>Шанс к 0<\/th>/.test(h), 'колонка есть в шапке таблицы открытых позиций');
  ok(/\$\{_jRecoverCell\(p\.unrealizedPct\)\}/.test(h), 'и заполняется от текущей просадки');
}

console.log('\nМобильная: та же справка строкой');
{
  const m = read('public/mobile/index.html');
  const i = m.indexOf('const _RECOVER_M = [');
  const src = m.slice(i, m.indexOf('\n    // ── Journal + Paper Bot', i));
  const ctx = { String, Math };
  vm.createContext(ctx);
  vm.runInContext(src + ';this.note = _recoverNote;', ctx);

  ok(ctx.note(null) === '' && ctx.note(4) === '' && ctx.note(-3) === '', 'без просадки строки нет');
  ok(/к 0 за месяц 67%/.test(ctx.note(-12)), 'на −12% сказано 67%', ctx.note(-12).replace(/<[^>]+>/g, ''));
  ok(/к 0 за месяц 24%/.test(ctx.note(-31)), 'на −31% сказано 24%');
  ok(/25%\?/.test(ctx.note(-57)), 'на большой глубине число помечено вопросом — выборка мала');
  ok(/_recoverNote\(pos\.unrealizedPct\)/.test(m), 'и подставляется в список открытых позиций');

  // Числа в обеих вёрстках обязаны совпадать: однажды они разошлись
  const d = read('public/index.html');
  for (const [at, w30] of [[10, 67], [20, 40], [30, 24], [45, 25]]) {
    const inD = new RegExp('at: ' + at + ',[^}]*w30: ' + w30).test(d);
    const inM = new RegExp('at: ' + at + ', w30: ' + w30).test(m);
    ok(inD && inM, 'полоса −' + at + '% одинакова в обеих вёрстках');
  }
}

console.log(bad ? '\nПЛОХО: ' + bad : '\nвсё зелено');
process.exit(bad ? 1 : 0);
