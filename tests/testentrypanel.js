// Панель «Лучший вход по рынку»: показывает то, что нашёл широкий скан,
// и честно говорит, когда порог не взял никто.
const fs = require('fs'), vm = require('vm');
const src = fs.readFileSync('public/index.html', 'utf8');
// Константа и панель лежат в разных местах файла — берём два куска, а не
// всё между ними: посередине семь тысяч строк чужого кода.
// Константа теперь стоит рядом с единственным потребителем — берём один кусок.
const ps = src.indexOf('    // 40 — минимальный порог, при котором превышение положительно в ОБА');
const pe = src.indexOf('    async function loadMicroScalp() {', ps);
const code = src.slice(ps, pe);
if (ps < 0 || pe < 0) { console.log('  FAIL  панель не найдена в файле'); process.exit(1); }

const box = { innerHTML: '' };
// Строка проверки вперёд живёт в СВОЁМ элементе и берёт СВОЙ запрос —
// без разделения она писалась в никуда, и её проверки молча проходили мимо.
const fwd = { innerHTML: '' };
let payload = null;      // ответ /api/entry-scan
let paper = null;        // ответ /api/entry-paper
const fresh = [];
const ctx = {
  console, JSON, Math, Date,
  trackFreshness: (id, j) => { fresh.push([id, j && j.at]); },
  document: { getElementById: id => id === 'entryScanBox' ? box : id === 'entryPaper' ? fwd : null },
  fetch: async (url) => ({ json: async () => String(url).includes('entry-paper') ? paper : payload }),
};
vm.createContext(ctx);
vm.runInContext(code, ctx);

let bad = 0;
const ok = (c, n, d) => { if (!c) bad++; console.log('  ' + (c ? 'ok  ' : 'FAIL') + '  ' + n + (d ? '   ' + d : '')); };
const txt = () => box.innerHTML.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
// Подсказки — то, что ушло с экрана, но обязано остаться в разметке
const tipOf = (el) => (el.innerHTML.match(/title="([^"]*)"/g) || []).join(' ');
const tip = () => tipOf(box);
// Спред теперь часть гейта: цель +0.30%, и если спред шире цели, сделка не
// может выйти в плюс. По умолчанию ставим узкий, отдельные проверки его меняют.
const coin = (c, pct, why, fall, rec, inList, spread) => ({ coin: c, price: 1.2345, rsi: 44, pullbackPct: 0.6,
  spreadPct: spread === undefined ? 0.05 : spread, dayFallPct: fall,
  recovery: rec === undefined ? null : rec, inListMin: inList == null ? null : inList, entryValue: { pct, why } });

(async () => {
  // const внутри vm не виден снаружи, поэтому порог проверяем по выводу

  payload = {
    success: true, total: 49, results: [
      coin('NEAR', 100, 'откат 0.65%, RSI 44', 12.4, { hour: 86, stuck: 0.0 }, 2100),
      coin('AERO', 100, 'откат 0.4%, RSI 45', 4.0, { hour: 68, stuck: 2.4 }, 10),
      // Только что появилась: в колонке срока должен быть прочерк, а не ноль.
      coin('FRESH', 90, 'откат 0.5%, RSI 42', 5.0, { hour: 68, stuck: 2.6 }, null),
      // Широкий спред не пускает: цель +0.30%, и спред шире цели делает
      // сделку заведомо убыточной, каким бы глубоким ни было падение.
      coin('WIDE', 100, 'откат 0.5%, RSI 40', 8.0, { hour: 74, stuck: 1.7 }, 5, 0.9),
      // Нет данных о падении — отказ, а не разрешение.
      coin('FET', 72, 'откат 0.55%, RSI 49', null, null),
      coin('XRP', 23, 'откат 0.31%, RSI 51', 0.5, { hour: 56, stuck: 4.4 }),
    ],
  };
  await ctx.loadEntryScan();
  let t = txt();
  ok(/Рейтинг отката/.test(t), 'заголовок называет содержание, а не обещает прибыль');
  ok(fresh.length && fresh[0][0] === 'entryAgo', 'счётчик свежести получает данные скана', JSON.stringify(fresh[0]));
  ok(/entryAgo/.test(box.innerHTML), 'и его место есть в заголовке');
  // Порог сменился с балла на глубину падения: балл вперёд себя не
  // подтвердил (66% против 70% у контроля), глубина делит обе группы.
  ok(/падение от 3%/.test(t), 'подпись называет действующий порог', t.slice(0, 70));
  ok(!/порог 40/.test(t), 'прежнего порога по баллу в подписи нет');
  ok(/49 монет/.test(t), 'размер вселенной назван — это не десятка микро-скальпа', t.slice(0, 70));
  ok(/NEAR/.test(t) && /AERO/.test(t), 'прошедшие порог по глубине показаны');
  ok(!/XRP/.test(t), 'мелкое падение в список не попало');
  ok(!/WIDE/.test(t), 'спред шире цели не пускает даже при глубоком падении');
  ok(!/FET/.test(t), 'нет данных о падении — отказ, а не разрешение');
  // Описание ушло с экрана в подсказку заголовка — но не пропало. Там
  // записано, ПОЧЕМУ список отсортирован по возврату, а не по баллу; забыть
  // это значит через месяц снова отсортировать по ВХОДу и снова получить то
  // же опровержение.
  ok(!/Порядок — по вероятности/.test(t), 'описание не занимает экран');
  ok(/Порядок — по вероятности возврата/.test(tip()), 'но осталось в подсказке заголовка');
  // Доля возврата теперь сложена из ДВУХ признаков, и оба проверены
  // разделением по времени. Прежняя подсказка знала только глубину.
  ok(/ОТКАТ от получасового максимума/.test(tip()), 'подсказка называет второй признак');
  ok(/добавляет 11-18 пунктов/.test(tip()), 'и его вклад числом');
  ok(/Балл ВХОД возврат НЕ предсказывает/.test(tip()),
    'и прямо говорит, что балл смотреть не нужно');
  ok(/ни в большую, ни в меньшую сторону/.test(tip()),
    'в том числе не в меньшую — «брать поменьше» тоже неверно');
  ok(/ранжирует откаты, а не обещает прибыль/.test(tip()), 'сказано, что прибыли список не обещает');
  // Польза порога вперёд НЕ подтверждена: сейчас +0.165 при погрешности
  // ±0.143, и разрыв сокращается по мере накопления данных. Утверждать её
  // подсказка не вправе — она должна сказать, что проверка идёт.
  ok(/обе группы журнала в минусе/.test(tip()), 'подсказка говорит, что прибыли нет');
  ok(/подтверждения пока нет/.test(tip()), 'и что польза порога пока не подтверждена');
  ok(!/но убыток сокращает[.,]/.test(tip()), 'а не выдаёт её за установленную');
  // Жёстко вписанное число рядом с живым счётчиком может только устареть:
  // в подсказке стояло +0.274, а журнал уже показывал +0.216.
  ok(!/\+0\.\d+ п\.п\. против контроля/.test(tip()),
    'величина преимущества не вписана руками, а берётся из журнала');
  ok(box.innerHTML.includes('rgba(0,229,160,0.10)'), 'проходящие подсвечены');

  const keepMain = payload;
  // Откат — второй признак, и порог 1.5% обязан быть виден без пересчёта
  payload = { success: true, total: 49, recoveryMeasuredAt: '2026-09-09', gate: { fallPct: 3, spreadPct: 0.3 },
    results: [
      { coin: 'DEEP', price: 1.2345, rsi: 40, pullbackPct: 1.7, spreadPct: 0.05, dayFallPct: 8.0,
        recovery: { hour: 87, stuck: 1.1, deep: true }, inListMin: 10, entryValue: { pct: 0, why: '' } },
      { coin: 'FLAT', price: 1.2345, rsi: 40, pullbackPct: 0.6, spreadPct: 0.05, dayFallPct: 8.0,
        recovery: { hour: 73, stuck: 2.0, deep: false }, inListMin: 10, entryValue: { pct: 100, why: '' } },
    ] };
  await ctx.loadEntryScan();
  ok(/1.7%/.test(txt()) && /0.6%/.test(txt()), 'оба отката показаны');
  ok(/#00e5a0[^>]*>1\.7%/.test(box.innerHTML.replace(/\s+/g, ' ')) || box.innerHTML.includes('#00e5a0'),
    'глубокий откат помечен цветом');
  // Монета с баллом 0, но глубоким откатом должна стоять ВЫШЕ монеты с
  // баллом 100 и мелким откатом — порядок задаёт сервер, панель его хранит
  ok(txt().indexOf('DEEP') < txt().indexOf('FLAT'), 'порядок с сервера не переставляется панелью');
  // Возвращаем прежнюю фикстуру: дальше идут проверки, написанные под неё.
  // Забыть это я уже успел однажды — половина набора проходила мимо.
  payload = keepMain;
  await ctx.loadEntryScan();
  t = txt();

  // Направление рынка: описание обстановки, а не сигнал. Проверяется и то,
  // что оно НЕ советует покупать — эффект направления на доли возврата не
  // пережил разделения по времени (+13.9 в первой половине, +0.1 во второй).
  const mkt = async (m) => {
    payload.market = m;
    await ctx.loadEntryScan();
    return box.innerHTML.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  };
  const base = { success: true, total: 49, recoveryMeasuredAt: '2026-09-07', results: payload.results };
  payload = { ...base };
  let m = await mkt({ coins: 46, up: 34, medChg24: 0.8, btcChg24: 2.4 });
  ok(/Рынок растёт/.test(m), 'рост рынка назван', m.slice(m.indexOf('Рынок'), m.indexOf('Рынок') + 60));
  ok(/34 из 46 монет в плюсе за сутки/.test(m), 'ширина рынка показана числом');
  ok(/BTC \+2.4%/.test(m), 'ход BTC показан');
  ok(/обычная монета \+0.8%/.test(m), 'ход обычной монеты показан');
  // Среднее тянула одна разогнавшаяся монета: при 30 из 48 в плюсе выходило
  // +3.05%, тогда как медиана давала 0.80%.
  ok(!/в среднем/.test(m), 'и это не среднее арифметическое');
  ok(/медианой, а не средним/.test(tip()), 'подсказка называет, чем меряется');
  ok(m.indexOf('Рынок растёт') < m.indexOf('монета возврат'), 'индикатор стоит над таблицей');
  ok(/признак не воспроизвёлся|не воспроизвёлся/.test(tip()),
    'подсказка честно говорит, что направление возвраты не предсказывает');
  ok(!/покупай|покупать смелее|хороший момент/i.test(m), 'и строка ничего не советует');

  m = await mkt({ coins: 46, up: 9, medChg24: -1.2, btcChg24: -2.7 });
  ok(/Рынок падает/.test(m), 'падение рынка названо');
  ok(/BTC -2.7%/.test(m), 'отрицательный ход BTC показан со знаком');
  m = await mkt({ coins: 46, up: 23, medChg24: 0.1, btcChg24: 0.2 });
  ok(/Рынок боком/.test(m), 'неопределённость названа, а не подана как рост');

  // Нет данных — нет строки. Пустой индикатор хуже отсутствующего: он
  // выглядит как «рынок никуда не движется».
  m = await mkt(null);
  ok(!/Рынок/.test(m), 'без данных индикатор не рисуется');
  m = await mkt({ coins: 46, up: 34, medChg24: 0.8, btcChg24: null });
  ok(/Рынок растёт/.test(m) && !/BTC/.test(m), 'без хода BTC остальное всё равно показано');
  payload = { ...base };
  await ctx.loadEntryScan();
  t = txt();

  // возврат: своя колонка, свой цвет, и он не смешан с ВХОДОМ
  ok(/↩ 86%/.test(t) && /↩ 68%/.test(t), 'доля возвратов показана по каждой монете', t.slice(0, 120));
  ok(box.innerHTML.includes('#00e5a0') && box.innerHTML.includes('#f5843a'),
    'надёжный возврат зелёный, слабый оранжевый');
  ok(/14 844 замера по монетам из этого же списка/.test(tip()),
    'подсказка называет размер замера и ту же совокупность, что показывает панель');

  // затянувшийся сигнал должен быть виден: TAO висел 35 часов и выглядел новым
  // срок теперь в своей колонке таблицы, а не подписью в строке
  ok(/35 ч/.test(t), 'долго висящая монета помечена сроком', t.slice(0, 140));
  // Возврат и откат стоят рядом: это два признака одной оценки.
  ok(/монета возврат откат за сутки RSI вход в списке/.test(t), 'колонки постоянные и подписаны');
  ok(/\$1.2345|\$1.234/.test(t), 'цена монеты показана');
  const freshRow = t.split('FRESH')[1] || '';
  ok(/—/.test(freshRow.slice(0, 60)), 'у свежей монеты в колонке срока прочерк', freshRow.slice(0, 60));
  ok(!/↩\s*(null|undefined|NaN)/.test(t), 'пустой возврат нигде не рисуется', t);

  // Прочерк за сутки обязан называть причину: истории не хватило, а не
  // «данных нет вообще». Занижённый суточный максимум иначе неотличим от
  // честного отказа — а он сажает монету в более мелкую строку таблицы.
  const keepPayload = payload;
  payload = { success: true, total: 49, recoveryMeasuredAt: '2026-09-07',
    results: [{ coin: 'GAPPY', price: 1.2345, rsi: 44, pullbackPct: 0.6, dayFallPct: null,
      dayCoverH: 3.2, recovery: null, inListMin: 5, entryValue: { pct: 90, why: 'откат 0.6%' } }] };
  await ctx.loadEntryScan();
  ok(/истории всего 3.2 ч/.test(tip()), 'прочерк за сутки объяснён нехваткой истории');
  ok(!/↩\s*(null|undefined|NaN)/.test(txt()), 'и возврат при этом не выдуман');
  payload = keepPayload;
  await ctx.loadEntryScan();
  t = txt();

  // Клик обязан быть рабочим: JSON.stringify рвал атрибут двойными кавычками
  ok(/onclick="selectCoinForTrade\('NEAR'\)"/.test(box.innerHTML),
    'клик подставляет монету и атрибут не разорван', (box.innerHTML.match(/onclick="[^"]*"/) || [''])[0]);
  ok(!/onclick="[^"]*"[A-Z]/.test(box.innerHTML), 'имя монеты не вываливается наружу атрибута');

  payload = { success: true, total: 49, results: [coin('XRP', 23, 'откат 0.31%, RSI 51'), coin('DOT', 8, 'откат 0.22%, RSI 55')] };
  await ctx.loadEntryScan();
  t = txt();
  ok(/Порог не взял никто/.test(t), 'пустой результат объяснён', t.slice(-60));
  ok(/XRP/.test(t) && /DOT/.test(t), 'ближайшие всё равно видны');
  ok(!box.innerHTML.includes('rgba(0,229,160,0.10)'), 'и не подсвечены как проходящие');

  // отвалившийся скан: список показан, но помечен устаревшим
  payload = { success: true, total: 50, staleSince: Date.now(), recoveryMeasuredAt: '2026-09-07',
    results: [coin('NEAR', 100, 'откат 0.65%, RSI 44', 12.4, { hour: 86, stuck: 0.0 }, 5)] };
  await ctx.loadEntryScan();
  ok(/список устарел/.test(txt()), 'отказ биржи назван, а не спрятан', txt().slice(0, 110));
  ok(/NEAR/.test(txt()), 'при этом прежний список всё равно показан');

  // возраст замера виден
  ok(/Замер 2026-09-07/.test(tip()), 'дата замера возвратов в подсказке');

  // Строка проверки вперёд обязана ставить впереди ту величину, где разница
  // есть: доля возвратов у групп почти одинакова, отличается доходность.
  payload = { success: true, total: 50, recoveryMeasuredAt: '2026-09-07',
    results: [coin('NEAR', 100, 'откат 0.65%, RSI 44', 12.4, { hour: 75, stuck: 0.5 }, 5)] };
  paper = { success: true, open: 38, openControl: 19, needPct: 0.3, startedAt: Date.now() - 5e7,
    overall: { n: 230, hitHour: 66, m5: -0.028, m15: -0.044, m60: -0.093, m60se: 0.085, mae: -0.607 },
    control: { n: 381, hitHour: 65, m5: -0.075, m15: -0.05, m60: -0.367, m60se: 0.094, mae: -0.703 },
    promiseVsFact: [{ label: '6-10%', n: 46, promised: 72, actual: 76 }], trades: [] };
  await ctx.loadEntryScan();
  t = fwd.innerHTML.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  ok(/через час −0.093% против −0.367% у контроля/.test(t.replace(/-/g, '−')),
    'доходность обеих групп на видном месте', t.slice(t.indexOf('Проверка вперёд'), t.indexOf('Проверка вперёд') + 120));
  ok(/разница \+0.274 ±0.127/.test(t), 'разница с погрешностью названа');
  ok(!/в пределах погрешности/.test(t), 'отличимая разница не помечена как шум');
  ok(t.indexOf('через час') < t.indexOf('до цели дошли'), 'доходность идёт перед долей возвратов');
  ok(!/менее убыточной/.test(t), 'пояснение не занимает вторую строку');
  ok(/менее убыточной, а не прибыльной/.test(tipOf(fwd)), 'но сказано в подсказке строки');
  ok(/обещано\/вышло/.test(tipOf(fwd)), 'и обещанное против вышедшего там же');
  ok(!/обещано\/вышло/.test(t), 'а на экране остались только числа');

  // неотличимая разница должна быть помечена
  paper.control = { n: 381, hitHour: 65, m5: 0, m15: 0, m60: -0.13, m60se: 0.094, mae: -0.7 };
  await ctx.loadEntryScan();
  ok(/в пределах погрешности/.test(fwd.innerHTML), 'неотличимая разница помечена как шум');

  payload = { success: true, total: 0, results: [], scanning: true };
  await ctx.loadEntryScan();
  ok(/Первый скан/.test(txt()), 'пустой скан объяснён, а не показан нулями');

  payload = { success: false, error: 'нет данных' };
  const before = box.innerHTML;
  await ctx.loadEntryScan();
  ok(box.innerHTML === before, 'при отказе success:false панель сохраняет прежнее');

  // а вот поломка обязана быть видимой, а не проглоченной
  ctx.fetch = async () => { throw new Error('HTTP 500'); };
  await ctx.loadEntryScan();
  ok(/недоступна: HTTP 500/.test(txt()), 'сбой назван причиной, а не пустотой', txt());

  console.log(bad ? '\nПРОБЛЕМ: ' + bad : '\nвсе проверки прошли');
})();
